#!/bin/sh
# present.hlsl to present_spirv.h for the Vulkan renderer with glslc (shaderc), the bindings gpu/spirv.h gives the
# registers; run after editing the shader, commit both. build.bat makes the D3D12 renderer's present_shaders.h.
set -e
cd "$(dirname "$0")"
out=present_spirv.h
echo "// generated by build_spirv.sh from present.hlsl: do not edit" > "$out"
echo "#pragma once" >> "$out"
echo "#include <cstdint>" >> "$out"
for pair in vs:vert:kPresentVsSpv ps_easu:frag:kPresentEasuSpv ps_final:frag:kPresentFinalSpv ps_hdr:frag:kPresentHdrSpv; do
    entry=${pair%%:*}
    rest=${pair#*:}
    stage=${rest%%:*}
    name=${rest#*:}
    glslc -x hlsl -fshader-stage="$stage" -fentry-point="$entry" -O -fhlsl-offsets -fhlsl-iomap \
        -fubo-binding-base 0 -ftexture-binding-base 2 -fsampler-binding-base 6 --target-env=vulkan1.3 \
        -mfmt=c -o "$entry.inc" present.hlsl
    printf "inline const uint32_t %s[] = " "$name" >> "$out"
    cat "$entry.inc" >> "$out"
    echo ";" >> "$out"
    rm -f "$entry.inc"
done
